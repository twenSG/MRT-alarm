// Run once: node scripts/fetch-bus-stops.js
// Fetches all bus stops from LTA DataMall and writes them as a static JS module
// Usage: LTA_API_KEY=your_key node scripts/fetch-bus-stops.js

const fs = require("fs");
const path = require("path");

const API_KEY = process.env.LTA_API_KEY;
if (!API_KEY) { console.error("Set LTA_API_KEY env var"); process.exit(1); }

async function fetchAll() {
  const stops = [];
  let skip = 0;
  while (true) {
    const res = await fetch(
      `https://datamall2.mytransport.sg/ltaodataservice/BusStops?$skip=${skip}`,
      { headers: { AccountKey: API_KEY } }
    );
    const data = await res.json();
    const batch = data.value || [];
    stops.push(...batch);
    console.log(`Fetched ${stops.length} stops so far...`);
    if (batch.length < 500) break;
    skip += 500;
  }
  return stops;
}

fetchAll().then(stops => {
  // Compact format: { "BusStopCode": [lat, lng, "Name"], ... }
  const compact = {};
  for (const s of stops) {
    compact[s.BusStopCode] = [s.Latitude, s.Longitude, s.Description];
  }

  const out = `// Auto-generated by scripts/fetch-bus-stops.js — do not edit manually
// Last updated: ${new Date().toISOString().slice(0, 10)}
// ${stops.length} bus stops

const BUS_STOPS = ${JSON.stringify(compact)};
export default BUS_STOPS;
`;

  const outPath = path.join(__dirname, "../src/busStops.js");
  fs.writeFileSync(outPath, out);
  console.log(`\nWrote ${stops.length} stops to src/busStops.js (${Math.round(out.length / 1024)}kb)`);
}).catch(err => { console.error(err); process.exit(1); });
